import { describe, expect, it } from 'vitest'
import { ago, dateLong, dateTip } from '../src/ui/format'

// 날짜 툴팁 — 적힌 시각 그대로, 00:00은 날짜만
describe('날짜 툴팁 글자 (ui/format)', () => {
  const now = Date.parse('2026-11-27T12:00:00+09:00')
  it('요일 · 시각, 00:00:00이면 시각 뺌, 보는 사람 시간대로 안 바꿈', () => {
    expect(dateLong('2026-11-03T22:15:00+09:00')).toBe('2026년 11월 3일 (화) 22:15')
    expect(dateLong('2026-11-02T00:00:00+09:00')).toBe('2026년 11월 2일 (월)')
    expect(dateLong('2026-01-01T09:05:00-05:00')).toBe('2026년 1월 1일 (목) 09:05')
  })
  it('얼마 전 — 어제 · n일 · n주 · n개월 · n년', () => {
    expect(ago('2026-11-26T12:00:00+09:00', now)).toBe('어제')
    expect(ago('2026-11-24T12:00:00+09:00', now)).toBe('3일 전')
    expect(ago('2026-11-03T22:15:00+09:00', now)).toBe('3주 전')
    expect(ago('2026-06-01T00:00:00+09:00', now)).toBe('5개월 전')
    expect(ago('2024-11-01T00:00:00+09:00', now)).toBe('2년 전')
  })
  it('고친 날이 다른 날이면 두 줄', () => {
    expect(dateTip('2026-11-03T22:15:00+09:00', '2026-11-03T23:00:00+09:00', now)).toBe('쓴 날 2026년 11월 3일 (화) 22:15 · 3주 전')
    expect(dateTip('2026-11-03T22:15:00+09:00', '2026-11-25T23:45:17+09:00', now)).toBe('쓴 날 2026년 11월 3일 (화) 22:15 · 3주 전\n고친 날 2026년 11월 25일 (수) 23:45')
  })
})
